/* 'MMDD이름,MMDD이름' 문자열 → {MMDD: 이름} */
function kcParse(str){
  var o = {}, a = str ? str.split(',') : [];
  for(var i = 0; i < a.length; i++) o[a[i].slice(0, 4)] = a[i].slice(4);
  return o;
}

var kcCache = {};
/* 그 해의 { 'MM-DD': {name, kind} } 를 만들어 캐시한다.
   kind — 'holi'(공휴일) | 'term'(절기·기념일) */
function kcYear(y){
  if(kcCache[y]) return kcCache[y];
  var map = {}, k, o, i;

  /* 절기 — 달은 고정(1월 소한·대한 … 12월 대설·동지) */
  var t = KTERM[y];
  if(t) for(i = 0; i < 24; i++){
    k = kcPad(Math.floor(i / 2) + 1) + '-' + t.substr(i * 2, 2);
    map[k] = {name: KTERM_NAME[i], kind: 'term'};
  }
  /* 잡절 · 양력 기념일 */
  o = kcParse(KMISC[y]);
  for(k in o) map[k.slice(0,2) + '-' + k.slice(2)] = {name: o[k], kind: 'term'};
  o = kcParse(KANNIV);
  for(k in o) map[k.slice(0,2) + '-' + k.slice(2)] = {name: o[k], kind: 'term'};
  /* 음력 기념일 — 그 해 양력으로 환산 */
  o = kcParse(KLANNIV);
  for(k in o){
    var s = kcSolar(y, +k.slice(0,2), +k.slice(2), false);
    if(s) map[s.slice(5)] = {name: o[k], kind: 'term'};
  }
  /* 공휴일이 가장 세다 — 마지막에 덮어쓴다 */
  o = kcParse(KHOLI[y]);
  for(k in o) map[k.slice(0,2) + '-' + k.slice(2)] = {name: o[k], kind: 'holi'};

  kcCache[y] = map;
  return map;
}

/* 설정에 등록한 음력 기념일(생일·기일)을 그 해 양력 날짜에 매핑 */
function kcEvents(y){
  var out = {};
  var list = (typeof cfg !== 'undefined' && cfg.lunarEvents) || [];
  for(var i = 0; i < list.length; i++){
    var e = list[i];
    var s;
    if(e.solar){
      /* 2월 30일처럼 없는 날짜를 고르면 그 달 말일로 당긴다 (조용히 사라지지 않게) */
      var last = new Date(Date.UTC(y, e.lm, 0)).getUTCDate();
      s = y + '-' + kcPad(e.lm) + '-' + kcPad(Math.min(e.ld, last));
    } else {
      s = kcSolar(y, e.lm, e.ld, e.leap);
    }
    if(s) out[s.slice(5)] = e.name;
  }
  return out;
}

/* 그 날에 해당하는 이름을 우선순위대로 모두 돌려준다.
   kind: 'event' 내가 등록한 기념일 / 'holi' 공휴일 / 'term' 절기·기념일

   등록한 기념일을 공휴일보다 앞에 둔다 — 공휴일은 날짜가 빨갛게 칠해지는 것만으로도
   알 수 있지만, 내 기일·생일은 여기 말고는 알 길이 없다. */
function kcMarkAll(key){
  var y = +key.slice(0, 4), md = key.slice(5), out = [];
  var showH = typeof cfg === 'undefined' || cfg.showHoliday !== false;
  var showT = typeof cfg !== 'undefined' && cfg.showTerm === true;

  var ev = kcEvents(y)[md];
  if(ev) out.push({name: ev, kind: 'event'});

  var hit = KHOLI[y] ? kcYear(y)[md] : null;
  if(hit && hit.kind === 'holi'){ if(showH) out.push(hit); }
  else if(hit && showT) out.push(hit);

  return out;
}

/* 달력 칸이 쓰는 대표 이름 하나. 없으면 null */
function kcMark(key){
  var a = kcMarkAll(key);
  return a.length ? a[0] : null;
}

/* 공휴일 여부만 (빨간 날짜 색칠용) — 설정 토글과 무관하게 사실을 답한다 */
function kcIsHoliday(key){
  var y = +key.slice(0, 4);
  if(!KHOLI[y]) return false;
  var hit = kcYear(y)[key.slice(5)];
  return !!(hit && hit.kind === 'holi');
}

