/* 양력 → 일련번호 (UTC 기준 일수). 시간대·서머타임 영향을 받지 않는다 */
function kcNum(y, m, d){ return Math.floor(Date.UTC(y, m - 1, d) / 86400000); }
function kcNumStr(s){ return kcNum(+s.slice(0,4), +s.slice(5,7), +s.slice(8,10)); }
function kcPad(n){ return n < 10 ? '0' + n : '' + n; }

/* 음력 연도의 시작(설날) 일련번호 */
function kcStart(ly){
  if(ly === KL_MAX + 1) return kcNumStr(KLUNAR_END);
  return KLUNAR[ly] ? kcNumStr(KLUNAR[ly].s) : null;
}

/* 음력 연도 ly 의 index 번째 달 → {num, leap} */
function kcMonthOf(ly, idx){
  var lp = KLUNAR[ly].leap;
  if(!lp || idx < lp) return {num: idx + 1, leap: false};
  if(idx === lp)      return {num: lp,     leap: true};
  return {num: idx, leap: false};
}

/* 양력 → 음력. 범위 밖이면 null (예외를 던지지 않는다) */
function kcLunar(y, m, d){
  var n = kcNum(y, m, d), ly = y;
  var s = kcStart(ly);
  if(s === null || n < s){ ly = y - 1; s = kcStart(ly); }
  if(s === null || ly < KL_MIN || ly > KL_MAX) return null;
  if(n >= kcStart(ly + 1)) return null;          /* 데이터 상한 밖 */
  var off = n - s, len = KLUNAR[ly].len;
  for(var i = 0; i < len.length; i++){
    var days = 29 + (+len.charAt(i));
    if(off < days){
      var mo = kcMonthOf(ly, i);
      return {ly: ly, lm: mo.num, ld: off + 1, leap: mo.leap};
    }
    off -= days;
  }
  return null;
}

/* 음력 → 양력 'YYYY-MM-DD'. 없는 날짜면 null.
   윤달을 요청했는데 그 해에 없으면 평달로 대체한다 (기념일 표시용) */
function kcSolar(ly, lm, ld, leap){
  var info = KLUNAR[ly];
  if(!info) return null;
  var len = info.len, idx = -1;
  for(var i = 0; i < len.length; i++){
    var mo = kcMonthOf(ly, i);
    if(mo.num === lm && mo.leap === !!leap){ idx = i; break; }
  }
  if(idx < 0 && leap){                            /* 윤달 없음 → 평달 */
    for(i = 0; i < len.length; i++){
      if(kcMonthOf(ly, i).num === lm && !kcMonthOf(ly, i).leap){ idx = i; break; }
    }
  }
  if(idx < 0) return null;
  var off = 0;
  for(i = 0; i < idx; i++) off += 29 + (+len.charAt(i));
  var mlen = 29 + (+len.charAt(idx));
  if(ld > mlen) ld = mlen;                        /* 30일이 없는 달 → 말일 */
  var dt = new Date((kcNumStr(info.s) + off + ld - 1) * 86400000);
  return dt.getUTCFullYear() + '-' + kcPad(dt.getUTCMonth() + 1) + '-' + kcPad(dt.getUTCDate());
}

/* 달력 칸에 쓸 짧은 음력 문자열. '6.18' / 윤달이면 '윤6.18' */
function kcLunarStr(y, m, d){
  var l = kcLunar(y, m, d);
  if(!l) return '';
  return (l.leap ? '윤' : '') + l.lm + '.' + l.ld;
}

